const mongoose = require('mongoose');

// A recurring weekly opening window, e.g. { dayOfWeek: 1, start: '09:00', end: '17:00' }
// means "Mondays, 09:00–17:00". Times are wall-clock in `timezone`.
const openingHourSchema = new mongoose.Schema(
  {
    dayOfWeek: { type: Number, required: true, min: 0, max: 6 }, // 0 = Sunday
    start: { type: String, required: true, match: /^([01]\d|2[0-3]):[0-5]\d$/ },
    end: { type: String, required: true, match: /^([01]\d|2[0-3]):[0-5]\d$/ },
  },
  { _id: false }
);

const resourceSchema = new mongoose.Schema(
  {
    name: { type: String, required: true, trim: true },
    description: { type: String, default: '' },
    capacity: { type: Number, required: true, min: 1 },
    price: { type: Number, required: true, min: 0 }, // in cents
    currency: { type: String, default: 'usd', lowercase: true, trim: true },
    durationMinutes: { type: Number, required: true, min: 5 },
    ownerId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    isActive: { type: Boolean, default: true },

    // Recurring availability. Bookable slots are generated by walking each
    // window in `durationMinutes` steps, so slots don't have to be created by
    // hand. An empty array means "no restriction" — any slot start is bookable.
    openingHours: { type: [openingHourSchema], default: [] },

    // IANA zone the opening hours are expressed in. Stored separately because
    // "Mondays 9am" means a different UTC instant across DST boundaries.
    timezone: { type: String, default: 'UTC' },
  },
  { timestamps: true }
);

resourceSchema.index({ name: 'text', description: 'text' });
// Supports the common "active resources, newest first" listing.
resourceSchema.index({ isActive: 1, createdAt: -1 });

module.exports = mongoose.model('Resource', resourceSchema);
